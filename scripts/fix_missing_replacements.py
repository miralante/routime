def process_file(filepath):
    if not filepath.endswith(('.js', '.html', '.css')):
        return 0
    
    try:
        with open(filepath, 'r', encoding='utf-8') as f:
            content = f.read()
    except:
        return 0
    
    original = content
    changes = 0
    
    for pattern, replacement in REPLACEMENTS:
        new_content = re.subn(pattern, replacement, content)
        if new_content[1] > 0:
            content = new_content[0]
            changes += new_content[1]
    
    if content != original:
        try:
            with open(filepath, 'w', encoding='utf-8') as f:
                f.write(content)
            return changes
        except:
            return 0
    return 0


def main():
    total_changes = 0
    files_changed = 0
    
    for root, dirs, files in os.walk(TOOLS_DIR):
        for fname in files:
            if not fname.endswith(('.js', '.html', '.css')):
                continue
            fpath = os.path.join(root, fname)
            n = process_file(fpath)
            if n:
                files_changed += 1
                total_changes += n
                print(f"[{n:3d}x] {fpath}")
    
    print(f"\nDone: {files_changed} files changed, {total_changes} total replacements.")


if __name__ == '__main__':
    main()
