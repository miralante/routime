#!/usr/bin/env python3
"""
Fix the specific mojibake sequences in the routime strings files.
These are all the same pattern: UTF-8 char → read as Latin-1 → re-encoded as UTF-8.
The correct mapping is based on the specific bytes found in the files.
"""
import os

FIXES = {
    # blocks strings.es.js
    b'\xc3\x83\xc2\xad': b'\xc3\xad',  # í
    b'\xc3\x83\xc2\xa9': b'\xc3\xa9',  # é
    b'\xc3\x83\xc2\xa1': b'\xc3\xa1',  # á
    b'\xc3\x83\xc2\xb3': b'\xc3\xb3',  # ó
    b'\xc3\x83\xc2\xba': b'\xc3\xba',  # ú
    b'\xc3\x83\xc2\xb1': b'\xc3\xb1',  # ñ
    b'\xc3\x83\xc2\x89': b'\xc3\x89',  # É
    b'\xc3\x83\xc2\x81': b'\xc3\x81',  # Á
    b'\xc3\x83\xc2\x93': b'\xc3\x93',  # Ó
    b'\xc3\x83\xc2\x9a': b'\xc3\x9a',  # Ú
    b'\xc3\x83\xc2\x91': b'\xc3\x91',  # Ñ
    b'\xc3\x83\xc2\x8d': b'\xc3\x8d',  # Í
    b'\xc3\x83\xc2\x80': b'\xc3\x80',  # À
    b'\xc3\x83\xc2\x87': b'\xc3\x87',  # Ç
    b'\xc3\x83\xc2\x8a': b'\xc3\x8a',  # Ê
    b'\xc3\x83\xc2\x94': b'\xc3\x94',  # Ô
    b'\xc3\x83\xc2\x96': b'\xc3\x96',  # Ö
    b'\xc3\x83\xc2\x9c': b'\xc3\x9c',  # Ü
    b'\xc3\x83\xc2\xa3': b'\xc2\xa3',  # £
    b'\xc3\x83\xc2\xa2': b'\xc2\xa2',  # ¢
    b'\xc3\x83\xc2\xab': b'\xc2\xab',  # «
    b'\xc3\x83\xc2\xbb': b'\xc2\xbb',  # »
    b'\xc3\x83\xc2\xbf': b'\xc2\xbf',  # ¿
    b'\xc3\x83\xc2\xae': b'\xc2\xae',  # ®
    b'\xc3\x83\xc2\xa9': b'\xc2\xa9',  # ©
    b'\xc3\x83\xc2\xbc': b'\xc2\xbc',  # ¼
    b'\xc3\x83\xc2\xbd': b'\xc2\xbd',  # ½
    b'\xc3\x83\xc2\xbe': b'\xc2\xbe',  # ¾
    b'\xc3\x83\xc2\x82': b'\xc3\x82',  # Â (from c3 83 c2 82)
    # Common â€ patterns
    b'\xc3\xa2\xe2\x82\xac\xc2\x9c': b'\xc5\x92',  # Œ
    b'\xc3\xa2\xe2\x82\xac\xc2\x9d': b'\xc5\x93',  # œ
    b'\xc3\xa2\xe2\x82\xac\xcb\x9d': b'\xc5\xb8',  # Ÿ
    b'\xc3\xa2\xe2\x82\xac\xe2\x80\x99': b'\xe2\x80\x99',  # '
    b'\xc3\xa2\xe2\x82\xac\xe2\x80\x9a': b'\xe2\x80\x9a',  # ‚
    b'\xc3\xa2\xe2\x82\xac\xe2\x80\x9c': b'\xe2\x80\x9c',  # "
    b'\xc3\xa2\xe2\x82\xac\xe2\x80\x9d': b'\xe2\x80\x9d',  # "
    b'\xc3\xa2\xe2\x82\xac\xe2\x80\x9e': b'\xe2\x80\x9e',  # "
    b'\xc3\xa2\xe2\x82\xac\xe2\x80\x93': b'\xe2\x80\x93',  # –
    b'\xc3\xa2\xe2\x82\xac\xe2\x80\x94': b'\xe2\x80\x94',  # —
    b'\xc3\xa2\xe2\x82\xac\xe2\x80\xa6': b'\xe2\x80\xa6',  # …
    b'\xc3\xa2\xe2\x82\xac\xe2\x80\xa0': b'\xe2\x80\xa0',  # †
    b'\xc3\xa2\xe2\x82\xac\xe2\x80\xa1': b'\xe2\x80\xa1',  # ‡
    b'\xc3\xa2\xe2\x82\xac\xc2\xae': b'\xc2\xae',  # ®
    b'\xc3\xa2\xe2\x82\xac\xc2\xa9': b'\xc2\xa9',  # ©
    b'\xc3\xa2\xe2\x82\xac\xcb\x9c': b'\xc5\x92',  # Œ
}

def fix_file(path):
    with open(path, 'rb') as f:
        data = f.read()
    original = data
    for bad, good in sorted(FIXES.items(), key=lambda x: -len(x[0])):
        data = data.replace(bad, good)
    if data != original:
        with open(path, 'wb') as f:
            f.write(data)
        print(f'  Fixed: {path}')

def main():
    base = 'routime/tools'
    for activity in sorted(os.listdir(base)):
        for sf in ['strings.es.js', 'strings.en.js']:
            path = os.path.join(base, activity, sf)
            if os.path.isfile(path):
                fix_file(path)

if __name__ == '__main__':
    main()
